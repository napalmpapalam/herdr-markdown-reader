// Vendors GitHub's emoji shortcodes as a table from each name to its emoji, for `:name:` in text.
// Run from the repository root: `node tools/build-emoji.mjs`. It needs npm and tar.
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const PACKAGE = "gemoji@8.1.0";
const OUT = "mods/markdown-reader/vendor/gemoji";

const work = mkdtempSync(join(tmpdir(), "gemoji-"));
try {
  const tarball = execFileSync("npm", ["pack", PACKAGE, "--silent", "--pack-destination", work], { encoding: "utf8" }).trim();
  execFileSync("tar", ["xzf", join(work, tarball), "-C", work]);
  const source = join(work, "package"), { gemoji } = await import(pathToFileURL(join(source, "index.js")).href);
  const table = Object.fromEntries(gemoji.flatMap(entry => entry.names.map(name => [name, entry.emoji])));
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  copyFileSync(join(source, "license"), join(OUT, "LICENSE"));
  writeFileSync(join(OUT, "table.js"), `// Generated by tools/build-emoji.mjs from ${PACKAGE} (MIT). Do not edit.\nexport default ${JSON.stringify(table)};\n`);
  console.log(`${Object.keys(table).length} shortcodes from ${PACKAGE} in ${OUT}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
