// Vendors the Material Icon Theme icons that the reader's file tree and search results use:
// every folder icon and the Markdown file icons, with a lookup table trimmed to them.
// Run from the repository root: `node tools/build-icons.mjs`. It needs npm and tar.
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const PACKAGE = "material-icon-theme@5.40.0";
const OUT = "mods/markdown-reader/vendor/material-icon-theme";
const MARKDOWN = /(^|\.)(md|markdown|mdown|mkd|mdx)$/i;

// The reader's lookup tries a name as written, then without its ".", "_", "-" or "__x__" decoration,
// so the table keeps one bare key per variant set.
const bare = name => name.replace(/^__(.+)__$/, "$1").replace(/^[._-]/, "");
const opened = id => id.endsWith("_light") ? `${id.slice(0, -6)}-open_light` : `${id}-open`;

function trim(names, keep, key) {
  const out = {};
  for (const [name, id] of Object.entries(names ?? {})) {
    if (!keep(name)) continue;
    const short = key(name.toLowerCase());
    if (out[short] && out[short] !== id) throw new Error(`${name} and another name both become "${short}"`);
    out[short] = id;
  }
  return out;
}

function tables(theme) {
  return {
    fileNames: trim(theme.fileNames, name => MARKDOWN.test(name), name => name),
    fileExtensions: trim(theme.fileExtensions, name => MARKDOWN.test(name), name => name),
    folderNames: trim(theme.folderNames, () => true, bare),
  };
}

const work = mkdtempSync(join(tmpdir(), "material-icon-theme-"));
try {
  const tarball = execFileSync("npm", ["pack", PACKAGE, "--silent", "--pack-destination", work], { encoding: "utf8" }).trim();
  execFileSync("tar", ["xzf", join(work, tarball), "-C", work]);
  const source = join(work, "package"), manifest = JSON.parse(readFileSync(join(source, "dist/material-icons.json"), "utf8"));
  const table = { file: manifest.fileExtensions.md, folder: manifest.folder, ...tables(manifest), light: tables(manifest.light) };
  const files = [table.file, ...[table, table.light].flatMap(t => [...Object.values(t.fileNames), ...Object.values(t.fileExtensions)])];
  const folders = [table.folder, ...Object.values(table.folderNames), ...Object.values(table.light.folderNames)];
  const ids = new Set([...files, ...folders, ...folders.map(opened)]);
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(join(OUT, "icons"), { recursive: true });
  for (const id of ids) copyFileSync(join(source, "dist", manifest.iconDefinitions[id].iconPath), join(OUT, "icons", `${id}.svg`));
  copyFileSync(join(source, "LICENSE"), join(OUT, "LICENSE"));
  writeFileSync(join(OUT, "table.js"), `// Generated by tools/build-icons.mjs from ${PACKAGE} (MIT). Do not edit.\nexport default ${JSON.stringify(table)};\n`);
  console.log(`${ids.size} icons from ${PACKAGE} in ${OUT}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
